export function emitRendererEvent(channel: string, args: unknown[]): void {
  const listeners = rendererListeners.get(channel);
  if (!listeners || listeners.size === 0) {
    return;
  }
  const event = { sender: null };
  for (const listener of listeners) {
    listener(event, ...args);
  }
}

function handleIncomingMessage(message: MainToRendererMessage): void {
  if (message.type === "ipc-main-event") {
    emitRendererEvent(message.channel, message.args);
    return;
  }

  if (message.type === "ipc-renderer-invoke-result") {
    const pending = pendingInvokes.get(message.requestId);
    if (!pending) {
      return;
    }
    pendingInvokes.delete(message.requestId);
    if (message.ok) {
      pending.resolve(message.result);
      return;
    }
    pending.reject(new Error(message.errorMessage));
    return;
  }

  if (message.type === "message-port-message") {
    messagePorts.get(message.portId)?.postMessage(message.data);
    return;
  }

  if (message.type === "message-port-close") {
    const port = messagePorts.get(message.portId);
    messagePorts.delete(message.portId);
    port?.close();
    return;
  }

  if (message.type === "workspace-directory-entries-result") {
    const pending = pendingDirectoryEntries.get(message.requestId);
    if (!pending) {
      return;
    }
    pendingDirectoryEntries.delete(message.requestId);
    if (message.ok) {
      pending.resolve(message.result);
      return;
    }
    pending.reject(new Error(message.errorMessage));
  }
}

function flushOutboundQueue(): void {
  if (!socket || socket.readyState !== WebSocket.OPEN || !transportReady)
    return;
  for (const message of outboundQueue) {
    if (message.clientSequence <= lastSentClientSequence) continue;
    socket.send(JSON.stringify(message));
    lastSentClientSequence = message.clientSequence;
  }
}

function receiveSessionMessage(
  message: MainToRendererMessage & { sessionSequence?: number },
): void {
  if (
    message.sessionSequence !== undefined &&
    message.sessionSequence <= lastReceivedSequence
  )
    return;
  handleIncomingMessage(message);
  if (message.sessionSequence !== undefined) {
    lastReceivedSequence = message.sessionSequence;
    if (ackTimeoutId === null) {
      ackTimeoutId = window.setTimeout(() => {
        ackTimeoutId = null;
        if (socket?.readyState === WebSocket.OPEN) {
          socket.send(
            JSON.stringify({
              type: "ipc-session-ack",
              after: lastReceivedSequence,
            }),
          );
        }
      }, 30);
    }
  }
}

function scheduleReconnect(): void {
  if (reconnectTimeoutId !== null) {
    return;
  }
  reconnectTimeoutId = window.setTimeout(() => {
    reconnectTimeoutId = null;
    ensureSocket();
  }, RECONNECT_DELAY_MS);
}

function ensureSocket(): void {
  if (
    socket &&
    (socket.readyState === WebSocket.OPEN ||
      socket.readyState === WebSocket.CONNECTING)
  ) {
    return;
  }

  socket = new WebSocket(
    `${window.location.protocol === "https:" ? "wss:" : "ws:"}//${window.location.host}/__backend/ipc?browserSession=${browserSession}`,
  );
  transportReady = false;
  const connectedSocket = socket;
  const receiver = browserIpcCache(
    socket,
    (message) => receiveSessionMessage(message as MainToRendererMessage),
    () => {
      if (socket === connectedSocket) {
        transportReady = true;
        connectedSocket.send(
          JSON.stringify({
            type: "ipc-session-resume",
            after: lastReceivedSequence,
          }),
        );
        flushOutboundQueue();
      }
    },
    (error) => {
      console.error("[electron-stub] IPC cache recovery failed", error);
      connectedSocket.close(1011, "IPC cache recovery");
    },
  );
  socket.addEventListener("open", () => receiver.opened());
  socket.addEventListener("message", (event) => {
    try {
      const message = JSON.parse(String(event.data)) as MainToRendererMessage;
      const control = message as unknown as {
        type: string;
        resumed?: boolean;
        after?: number;
      };
      if (control.type === "ipc-session-ready") {
        // Reload only when the retained view actually expired or the server restarted.
        if (!control.resumed && lastReceivedSequence > 0)
          window.location.reload();
        return;
      }
      if (control.type === "ipc-session-client-ack") {
        while (
          outboundQueue.length &&
          outboundQueue[0]!.clientSequence <= (control.after ?? 0)
        ) {
          outboundQueue.shift();
        }
        return;
      }
      if (control.type === "ipc-session-pong") {
        if (pingTimeoutId !== null) window.clearTimeout(pingTimeoutId);
        pingTimeoutId = null;
        return;
      }
      receiver.receive(message);
    } catch (error) {
      console.error(
        "[electron-stub] failed to parse IPC bridge message",
        error,
      );
    }
  });
  socket.addEventListener("close", () => {
    receiver.close();
    if (socket !== connectedSocket) return;
    transportReady = false;
    lastSentClientSequence = 0;
    scheduleReconnect();
  });
  socket.addEventListener("error", () => {
    scheduleReconnect();
  });
}

function enqueueMessage(message: RendererToMainMessage): void {
  outboundQueue.push({ ...message, clientSequence: ++clientSequence });
  ensureSocket();
  flushOutboundQueue();
}

function resumeConnection(): void {
  if (reconnectTimeoutId !== null) window.clearTimeout(reconnectTimeoutId);
  reconnectTimeoutId = null;
  ensureSocket();
  const currentSocket = socket;
  if (currentSocket?.readyState === WebSocket.OPEN && pingTimeoutId === null) {
    currentSocket.send(JSON.stringify({ type: "ipc-session-ping" }));
    pingTimeoutId = window.setTimeout(() => {
      pingTimeoutId = null;
      if (socket === currentSocket) currentSocket.close();
    }, 5000);
  }
}
document.addEventListener("visibilitychange", () => {
  if (document.visibilityState === "visible") resumeConnection();
});
window.addEventListener("online", resumeConnection);
window.addEventListener("pageshow", resumeConnection);
window.addEventListener("pagehide", (event) => {
  if (!event.persisted && socket?.readyState === WebSocket.OPEN) {
    socket.send(JSON.stringify({ type: "ipc-session-end" }));
  }
});

function nextRequestId(): string {
  requestCounter += 1;
  return `ipc_bridge_${requestCounter}`;
}

function invokeMain(channel: string, args: unknown[]): Promise<unknown> {
  const requestId = nextRequestId();
  return new Promise((resolve, reject) => {
    pendingInvokes.set(requestId, { resolve, reject });
    enqueueMessage({
      type: "ipc-renderer-invoke",
      requestId,
      channel,
      args,
    });
  });
}

function addIpcListener(channel: string, listener: IpcListener): void {
  const listeners = rendererListeners.get(channel) ?? new Set<IpcListener>();
  listeners.add(listener);
  rendererListeners.set(channel, listeners);
}

function shouldCloseSidebarForMemoryPath(path: string): boolean {
  return (
    path === "/" ||
    path.startsWith("/local/") ||
    path === "/skills" ||
    path === "/automations"
  );
}

export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function isUnhandledAddWorkspaceRootOptionMessage(value: unknown): value is {
  root?: unknown;
  type: "electron-add-new-workspace-root-option";
} {
  return (
    isRecord(value) &&
    value.type === "electron-add-new-workspace-root-option" &&
    typeof value.root !== "string"
  );
}

function isOpenInBrowserMessage(value: unknown): value is {
  type: "open-in-browser";
  url: string;
} {
  return (
    isRecord(value) &&
    value.type === "open-in-browser" &&
    typeof value.url === "string"
  );
}

function requestWorkspaceDirectoryEntries(
  directoryPath: string | null,
): Promise<WorkspaceDirectoryEntries> {
  const requestId = nextRequestId();
  return new Promise((resolve, reject) => {
    pendingDirectoryEntries.set(requestId, { resolve, reject });
    enqueueMessage({
      type: "workspace-directory-entries-request",
      requestId,
      directoryPath,
      directoriesOnly: true,
    });
  });
}

